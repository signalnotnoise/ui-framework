"""Generate portable skill references from shipped contracts and compiled examples."""
import argparse
from collections import defaultdict
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = {
    "SkillIconToolbarExample": "WPF-only compact toolbar: frame sizes are separate from native sizes. ApplyTheme before attaching the dedicated host; the Loaded handoff clears renderer-local padding so this scoped style owns it. Reapply after theme/contrast changes with the current system contrast flag so the quiet surface stays readable. Keep the framework template and Quiet appearance for feedback; arbitrary consumer templates retain their own responsibility.",
    "SkillLayoutExample": "Use Dock/Flex for finite space; stacks remain content-sized. A stack can itself be a weighted child of a flex container. Keep splitter state on the component.",
    "SkillStateExample": "Do not allocate State or Computed in Body. Retained fields survive builds; the constructor creates the derived value once.",
    "SkillRowsExample": "Do not use positions or fresh random keys. Key each row by a unique domain ID; ReplaceAll can reorder these identities. Removed rows lose local state. Offscreen retention is governed by the virtualization guide.",
    "SkillRowExample": "A retained row owns its editable value. Configure parent inputs separately from local state.",
}


def api_reference(root):
    version = ET.parse(root / "Directory.Build.props").findtext(".//Version")
    if not version:
        raise ValueError("Missing package version")
    output = ["# Shipped API reference", "", f"Package version: `{version}` (repository shipped baseline).", "",
              "Generated by `python tools/Update-SkillReference.py`; do not edit.", "",
              "These are exact PublicApiAnalyzers signatures, not compilable C#. `!` marks",
              "non-null references, `?` marks nullable types, and `->` introduces the return type.",
              "Inherited framework members and compiler-synthesized members may not be listed.",
              "For a different installed version, inspect that package's metadata instead.", ""]
    for project in ("UI Framework", "UI Framework.Wpf"):
        path = Path(project) / "PublicAPI.Shipped.txt"
        lines = [line for line in (root / path).read_text(encoding="utf-8-sig").splitlines()
                 if line.strip() and not line.startswith("#")]
        types = sorted((line for line in lines if " " not in line and "(" not in line), key=len, reverse=True)
        groups = defaultdict(list)
        for line in lines:
            declaration = re.sub(r"^(?:(?:static|readonly|abstract|virtual|override|sealed) )+", "", line)
            owner = next((name for name in types if declaration == name or declaration.startswith(name + ".")), None)
            if owner is None:
                raise ValueError(f"Unrecognized API owner in {path}: {line}")
            groups[owner].append(line)
        output += [f"## {project}", "", f"Source: `{path.as_posix()}`", ""]
        for owner in sorted(groups):
            output += [f"### {owner}", "", "```text", *sorted(groups[owner]), "```", ""]
    return "\n".join(output)


def examples_reference(root):
    output = ["# Compiled behavioral examples", "", "Generated by `python tools/Update-SkillReference.py`; do not edit.", "",
              "Each complete type below is compiled by UI Framework.Checks. SkillContractTests",
              "exercise state notifications, native layout and retained row identity. CompactIconButtonTests",
              "verify the scoped icon-toolbar recipe, geometry and native template feedback.", ""]
    for name, explanation in EXAMPLES.items():
        path = Path("tests/UI Framework.Checks/SkillExamples") / f"{name}.cs"
        source = (root / path).read_text(encoding="utf-8-sig").rstrip()
        output += [f"## {name}", "", explanation, "", f"Source: `{path.as_posix()}`", "", "```csharp", source, "```", ""]
    return "\n".join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, content in (("api-surface.md", api_reference(ROOT)), ("behavior-examples.md", examples_reference(ROOT))):
        path = ROOT / "skills/ui-framework/references" / name
        expected = content.encode("utf-8")
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_bytes(expected)
    if stale:
        parser.exit(1, "Stale skill references; run python tools/Update-SkillReference.py:\n" + "\n".join(stale) + "\n")
    print("Skill references are current." if args.check else "Skill references generated.")


if __name__ == "__main__":
    main()
